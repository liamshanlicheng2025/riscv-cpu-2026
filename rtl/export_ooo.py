#!/usr/bin/env python3
"""Regenerate portable course RTL from editable SystemVerilog (sv2v 0.0.13)."""
import argparse
import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "rtl/ooo"
NAMES = ["cpu_pkg", "decoder", "alu", "branch_unit", "muldiv", "memory_controller",
         "cpu_top", "v2_frontend", "v2_dcache", "v2_rename", "v2_select", "v2_read",
         "v2_ring_youngest", "v2_age_matrix", "v2_alu", "v2_add32", "v2_prepare_address",
         "ooo_recovery_flag", "ooo_head_select", "student_top"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sv2v", type=Path, default=ROOT / "build/tools/sv2v-Linux/sv2v")
    parser.add_argument("--output", type=Path, default=ROOT / "verilog/ooo_cpu.v")
    parser.add_argument("--param", action="append", default=[], metavar="NAME=INTEGER",
                        help="override an exported student_top parameter default")
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location("upstream_export", SOURCE / "upstream_export.py")
    exporter = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(exporter)
    paths = [SOURCE / (name + ".sv") for name in NAMES]
    exporter.ROOT = ROOT
    converted, _ = exporter.convert(paths, args.sv2v.resolve())
    parameters = {}
    for entry in args.param:
        name, value = entry.split("=", 1)
        value = int(value, 0)
        # Restrict overrides to the wrapper; internal parameters retain their bindings.
        start = converted.index("module student_top")
        wrapper, count = re.subn(r"(parameter integer " + re.escape(name) + r"\s*=\s*)[^;]+;",
                                lambda m: m[1] + str(value) + ";", converted[start:], count=1)
        if count != 1:
            parser.error("unknown student_top parameter: " + name)
        converted = converted[:start] + wrapper
        parameters[name] = value
    converted = ("// Derived from Galuisss/ACM-CPU, commit b76000b65bfa7ef9aca57ef27478ce33fa488791.\n"
                 "// Local adaptation: full PC/BTB addresses, 256 MiB RAM, parameterized course wrapper.\n"
                 "// Generated by rtl/export_ooo.py; edit rtl/ooo/*.sv and regenerate.\n" + converted)
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(converted)
    metadata = {
        "upstream": "https://github.com/Galuisss/ACM-CPU",
        "upstream_commit": "b76000b65bfa7ef9aca57ef27478ce33fa488791",
        "sources_sha256": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths},
        "exporter_sha256": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                            for p in (Path(__file__).resolve(), SOURCE / "upstream_export.py")},
        "parameters": parameters,
        "output_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
    }
    output.with_suffix(".metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(output)


if __name__ == "__main__":
    main()
